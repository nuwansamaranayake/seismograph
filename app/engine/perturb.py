"""Deterministic perturbation generators: irrelevance, order, and format.

A metamorphic invariant says "this change to the input must not change that field of the
output". These three changes need no model to produce, so they are generated by code:
the same seed input always yields the same variants, in the same order, and a contract
that declares them is executable with zero external keys. (Paraphrase is the one
perturbation that needs a model to propose it; see engine.metamorphic.)

A variant equal to the seed would measure nothing, so no generator ever returns it.
"""
from __future__ import annotations

import re
from itertools import permutations

# Sentences with no bearing on any probe. The second half are deliberate bait: they share
# vocabulary with a refund decision while stating nothing about this customer. A system
# that weighs them has a defect; a healthy one ignores both halves.
DISTRACTORS: tuple[str, ...] = (
    "The store's opening hours changed last month.",
    "The loyalty newsletter goes out on the first Monday of each month.",
    "The warehouse moved to a new address in the spring.",
    "The support team answers email within one working day.",
    "A different customer was refused a refund last week.",
    "Another shopper asked whether returns are ever refused.",
)

_SENTENCE = re.compile(r"[^.!?]+[.!?]+|[^.!?]+$")


def sentences(text: str) -> list[str]:
    """Split on terminal punctuation. Deliberately simple: probes are short prompts, and a
    splitter that guesses at abbreviations would make the variant set depend on a guess."""
    return [s.strip() for s in _SENTENCE.findall(text) if s.strip()]


def irrelevant_context(seed_input: str, k: int) -> list[str]:
    """Add one unrelated sentence, alternating before and after the seed."""
    out = []
    for i in range(k):
        distractor = DISTRACTORS[i % len(DISTRACTORS)]
        before = (i // len(DISTRACTORS)) % 2 == 0
        out.append(f"{distractor} {seed_input}" if before else f"{seed_input} {distractor}")
    return out


def reorderings(seed_input: str, k: int) -> list[str]:
    """Every sentence order except the original, cycled to k variants."""
    parts = sentences(seed_input)
    if len(parts) < 2:
        raise ValueError(
            "reordering needs an input of at least two sentences; "
            f"got {len(parts)}: {seed_input!r}"
        )
    orders = list(dict.fromkeys(
        " ".join(p) for p in permutations(parts) if " ".join(p) != " ".join(parts)))
    if not orders:
        raise ValueError(f"reordering needs sentences that differ; every order of {seed_input!r} "
                         "reads the same")
    return [orders[i % len(orders)] for i in range(k)]


def _formats(seed_input: str) -> list[str]:
    spaced = re.sub(r" ", "  ", seed_input)
    return [
        seed_input.upper(),
        seed_input.lower(),
        spaced,
        f"  {seed_input}  ",
        "\n".join(sentences(seed_input)) + "\n",
        seed_input.rstrip(".!?"),
    ]


def format_variants(seed_input: str, k: int) -> list[str]:
    """Same words, different surface: case, spacing, line breaks, trailing punctuation."""
    # The padded variant always differs from the seed, so `distinct` is never empty.
    distinct = [v for v in dict.fromkeys(_formats(seed_input)) if v != seed_input]
    return [distinct[i % len(distinct)] for i in range(k)]


# Keyed by the perturbation's name. contracts.Perturbation is a str enum, so its members
# look these up directly, and this module stays importable from contracts.py.
_GENERATORS = {
    "irrelevant_context": irrelevant_context,
    "reordering": reorderings,
    "format": format_variants,
}

DETERMINISTIC_PERTURBATIONS = frozenset(_GENERATORS)


def variants_for(perturbation: str, seed_input: str, k: int) -> list[str]:
    """k variants of the seed under one deterministic perturbation."""
    name = str(getattr(perturbation, "value", perturbation))
    if name not in _GENERATORS:
        raise ValueError(f"'{name}' has no deterministic generator")
    if k < 1:
        raise ValueError("k must be at least 1")
    return _GENERATORS[name](seed_input, k)
